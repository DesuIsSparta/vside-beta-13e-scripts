        log("initialization", "debug", findArg("-play", "$JournalPlayFile", "Missing <journal file>") @ "journal play file: " @ $JournalPlayFile);
        log("initialization", "debug", findArg("-playAndBreak", "$JournalPlayAndBreakFile", "Missing <journal file>") @ "journal play and break file: " @ $JournalPlayAndBreakFile);
