        log("initialization", "debug", findArg("-eval", "$EvalString", "Missing <script expression>") @ "evaluating expression: " @ $EvalString);
        log("initialization", "debug", findArg("-exec", "$ExecScript", "Missing <script file>") @ "executing script: " @ $ExecScript);
        log("initialization", "debug", "disabling display");
        log("initialization", "debug", "opening console");
