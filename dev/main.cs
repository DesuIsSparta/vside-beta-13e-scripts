    };
    function parseArgs() {
        Parent::parseArgs();
        echo("--------- Parsing MOD: Dev ---------");
        echo("My version: " @ " " @ $dev_kit_check_Version);
        echo("Binary version: " @ " " @ $dev_check_version);
        echo("Bad Dev Kit. You need to swap to the Dev Kit for this version.");
        echo("Dev Kit authorised.");
        $dev_kit_auth = 1;
        !(($dev_kit_check_Version $= $dev_check_version));
        $JournalRecordFile = "";
        $JournalPlayFile = "";
        $JournalPlayAndBreakFile = "";
        $JoinGameAddress = "";
        $Insecure = 0;
        $CommandLineMods = "";
        $NonInteractive = 0;
        log("initialization", "debug", "standalone flag set");
        log("initialization", "debug", findArg("-mission", "$MissionArg", "Missing <mission file>") @ "mission file: " @ $MissionArg);
        $MissionArg = strreplace($MissionArg, "\\", "/");
        !((findSwitch("-standAlone", "$StandAlone") SPC strchr($MissionArg, "\\") $= ""));
