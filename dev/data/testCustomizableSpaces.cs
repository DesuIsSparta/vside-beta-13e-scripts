function TEST_CS_EditPermissions::runTest(%this) {
    %mockPlayerA = new ScriptObject("") {
        class = 0 @ "MockTestPlayer";
    };
    %mockPlayerB = new ScriptObject("") {
        class = 0 @ "MockTestPlayer";
    };
    %name = "Blah Blah Space";
    %manager = SpaceManager::GetInstance();
    %thespace = %name.CreateSpaceNamed(%manager, TestCS_MockTriggerObj);
    %ret = %mockPlayerA.StartEditing(%thespace);
    "expected mockPlayerA to be able to edit the space".assert(%this, %ret);
    "expected mockPlayerA to be the same as space.currentEditor".assertSameObject(%this, %thespace.currentEditor, %mockPlayerA);
    %ret = %mockPlayerB.StartEditing(%thespace);
    "mockPlayerB should not be able to edit a space already being edited".assert(%this, !(%ret));
    %mockPlayerA.StopEditing(%thespace);
    "when mockPlayerA stops editing, we expect the current editor to be null".assert(%this, (%thespace.currentEditor == 0.0));
    %ret = %mockPlayerB.StartEditing(%thespace);
    "mockPlayerB should now be able to edit the space since no one else is".assert(%this, %ret);
    %mockPlayerB.OnPlayerRemoved(%manager);
    "when mockPlayerB is removed, he should no longer be editing the space either".assert(%this, (%thespace.currentEditor == 0.0));
    "if player is not editing the space, stopEditing should return false".assert(%this, !(%mockPlayerB.StopEditing(%thespace)));
    %thespace.delete();
    %mockPlayerA.delete();
    %mockPlayerB.delete();
};
