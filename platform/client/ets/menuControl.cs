    %idx = findWord(stack, %this.getId());
    layer;
    %i = 0;
    (-(1.0) != %idx);
    scroll.setVisible(0);
    %i = (1.0 + %i);
    getWord(stack, %i);
    stack = %this @ layer;
    layer @ getWords(stack, (1.0 + %idx));
    %this.makeFirstResponder(0);
    %this.hiliteCell(-(1.0), -(1.0));
    scroll.setVisible(0);
};
