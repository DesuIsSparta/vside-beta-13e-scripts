    %height = (2.0 + getWord(%this.getExtent(), 1));
    %left = (getWord(%scrollCtrl.getExtent(), 0) - %leftMargin);
    %top = %topMargin;
    %width = getWord(%scrollCtrl.getExtent(), 0);
